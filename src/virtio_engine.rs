// ----- Per-device queue counts (must match firmware constants) -----

pub const QUEUES_BLK: u32 = 1;
pub const QUEUES_NET: u32 = 2;
pub const QUEUES_CONSOLE: u32 = 2;
pub const QUEUES_RNG: u32 = 1;

#[inline]
pub fn num_queues_for_device(device_idx: u32) -> u32 {
    match device_idx {
        DEV_BLK | DEV_BLK1 | DEV_BLK2 => QUEUES_BLK,
        DEV_NET => QUEUES_NET,
        DEV_CONSOLE => QUEUES_CONSOLE,
        DEV_RNG => QUEUES_RNG,
        _ => 0,
    }
}

#[inline]
pub fn device_id_for_index(device_idx: u32) -> u32 {
    match device_idx {
        DEV_BLK | DEV_BLK1 | DEV_BLK2 => VIRTIO_ID_BLOCK,
        DEV_NET => VIRTIO_ID_NET,
        DEV_CONSOLE => VIRTIO_ID_CONSOLE,
        DEV_RNG => VIRTIO_ID_ENTROPY,
        _ => 0,
    }
}

/// VIRTIO_F_VERSION_1 lives at bit 32 of the 64-bit feature space —
/// bit 0 of the high half. Mirrors `VIRTIO_F_VERSION_1_HIGH_BIT` in
/// `brisc-firmware/virtio.c`.
pub const VIRTIO_F_VERSION_1_HIGH_BIT: u32 = 0x0000_0001;
/// VIRTIO_NET_F_MAC lives at bit 5 of the low half (features[0]).
/// Mirrors `VIRTIO_NET_F_MAC_BIT` in the firmware.
pub const VIRTIO_NET_F_MAC_BIT: u32 = 1 << 5;

/// Bits 0..31 (DEVICE_FEATURES_SEL=0) of the per-slot feature space.
/// Mirrors `DEVICE_TEMPLATE[].dev_feat_low` in the firmware.
#[inline]
pub fn dev_feat_low_for_index(device_idx: u32) -> u32 {
    match device_idx {
        DEV_NET => VIRTIO_NET_F_MAC_BIT,
        // Other populated slots advertise no low-half bits today.
        DEV_BLK | DEV_BLK1 | DEV_BLK2 | DEV_CONSOLE | DEV_RNG => 0,
        _ => 0,
    }
}

/// Bits 32..63 (DEVICE_FEATURES_SEL=1) of the per-slot feature space.
/// Today every populated slot advertises VIRTIO_F_VERSION_1; unused
/// slots advertise nothing.
#[inline]
pub fn dev_feat_high_for_index(device_idx: u32) -> u32 {
    match device_idx {
        DEV_BLK | DEV_BLK1 | DEV_BLK2 | DEV_NET | DEV_CONSOLE | DEV_RNG => {
            VIRTIO_F_VERSION_1_HIGH_BIT
        }
        _ => 0,
    }
}

// ----- Compile-time sanity -----

const _LAYOUT_INVARIANTS: () = {
    // Stats lives between code and the reg files; reg files don't
    // overlap with the shadow region.
    assert!(STATS_BASE >= CODE_BASE + CODE_SIZE);
    assert!(REGS_BASE >= STATS_BASE + STATS_SIZE);
    // Cross-module check: the control region (kick + completion
    // rings, hello/hello-ack, active-slots bitmap) lives between
    // STATS and REGS. A future bump of CTRL_SIZE that sneaks past
    // REGS_BASE would silently alias the kick ring onto the virtio
    // reg files. Pin both edges.
    assert!(crate::tensix_proto::CTRL_BASE >= STATS_BASE + STATS_SIZE);
    assert!(crate::tensix_proto::CTRL_BASE + crate::tensix_proto::CTRL_SIZE <= REGS_BASE);
    // 32 reg files (4 L2CPUs × 8 devices, 6 populated + 2 padding) of
    // 4 KiB each = 128 KiB, occupying [REGS_BASE, REGS_BASE+0x20000).
    assert!(NUM_SLOTS * REGS_PER_DEV == 32 * 0x1000);
    // Each L2CPU's window is DEVS_PER_L2CPU contiguous device reg files.
    assert!(PER_L2CPU_WINDOW_SIZE == DEVS_PER_L2CPU * REGS_PER_DEV);
    // DEVS_PER_L2CPU must stay a power of two so the firmware's
    // `slot % DEVS_PER_L2CPU` is a bitmask AND, not an __umodsi3 call.
    assert!(DEVS_PER_L2CPU.is_power_of_two());
    // Shadow region must sit above the reg-file region.
    assert!(SHADOW_BASE >= REGS_BASE + NUM_SLOTS * REGS_PER_DEV);
    // Shadow must end before BRISC_UART_BASE (0x40000 in
    // uart_layout.h) — a previous bump put SHADOW at 0x40000 which
    // overlapped the host-facing UART register file and caused
    // BRISC's shadow writes to land on top of UART regs (and vice
    // versa). The kick poller saw partial avail addresses on every
    // boot. Mirrored on the firmware side as `SHADOW_BASE` in
    // `brisc-firmware/virtio.c`.
    assert!(SHADOW_BASE + NUM_SLOTS * SHADOW_PER_DEVICE <= 0x0004_0000);

    // V2 layout cross-pin (#187). `tensix_proto::_V2_NUM_SLOTS` is
    // hard-coded as 32 to keep that module self-contained; this pins
    // it to `NUM_SLOTS` so a future change here can't silently desync
    // the V2 dirty / processed arrays.
    assert!(NUM_SLOTS == 32);
    assert!(
        crate::tensix_proto::CTRL_OFF_DIRTY + NUM_SLOTS * crate::tensix_proto::MAX_QUEUES_PER_SLOT
            <= crate::tensix_proto::CTRL_OFF_PROCESSED
    );
    assert!(
        crate::tensix_proto::CTRL_OFF_PROCESSED
            + NUM_SLOTS * crate::tensix_proto::MAX_QUEUES_PER_SLOT * 2
            <= crate::tensix_proto::CTRL_OFF_STATE_LOG
    );
    assert!(crate::tensix_proto::CTRL_OFF_V2_END <= crate::tensix_proto::CTRL_SIZE);
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn slot_indices_match_layout() {
        // 8 slots per L2CPU (6 populated + 2 padding for power-of-2):
        // blk / net / console / rng / blk1 / blk2 / unused / unused.
        assert_eq!(slot(0, DEV_BLK), 0);
        assert_eq!(slot(0, DEV_RNG), 3);
        assert_eq!(slot(0, DEV_BLK1), 4);
        assert_eq!(slot(0, DEV_BLK2), 5);
        // L2CPU 1's blk skips L2CPU 0's two padding slots (6, 7).
        assert_eq!(slot(1, DEV_BLK), 8);
        // Highest populated slot: L2CPU 3, BLK2.
        assert_eq!(slot(3, DEV_BLK2), 29);
    }

    #[test]
    fn slot_regs_base_matches_layout() {
        assert_eq!(slot_regs_base(0), 0x10000);
        assert_eq!(slot_regs_base(1), 0x11000);
        // Last slot (NUM_SLOTS - 1 = 31): REGS_BASE + 31*0x1000 = 0x2F000.
        assert_eq!(slot_regs_base(NUM_SLOTS - 1), 0x2F000);
    }

    #[test]
    fn l2cpu_windows_are_disjoint_and_contiguous() {
        for cpu in 0..NUM_L2CPUS {
            let base = l2cpu_window_base(cpu);
            assert_eq!(base, REGS_BASE + cpu * PER_L2CPU_WINDOW_SIZE);
            let blk_slot_base = slot_regs_base(slot(cpu, DEV_BLK));
            assert_eq!(blk_slot_base, base);
            let rng_slot_base = slot_regs_base(slot(cpu, DEV_RNG));
            assert_eq!(rng_slot_base, base + 3 * REGS_PER_DEV);
        }
    }

    #[test]
    fn embedded_firmware_is_nonempty_and_aligned() {
        assert!(!VIRTIO_FIRMWARE.is_empty());
        // First 4 bytes must be the entry stub `j main_entry` from
        // start.S, encoded as `0x0800006f`. If this changes the M3
        // firmware probably broke its calling convention.
        let entry = u32::from_le_bytes([
            VIRTIO_FIRMWARE[0],
            VIRTIO_FIRMWARE[1],
            VIRTIO_FIRMWARE[2],
            VIRTIO_FIRMWARE[3],
        ]);
        assert_eq!(entry, 0x0800_006f);
    }
}
