//! Host-side mirror of the M3 (#69) virtio-mmio register-file engine
//! layout in `brisc-firmware/include/virtio_layout.h`.
//!
//! The BRISC firmware lays out 16 virtio register files (4 L2CPUs ×
//! 4 devices) in the picked Tensix tile's L1 starting at
//! `REGS_BASE = 0x0001_0000`. The host (and eventually the L2CPU's
//! retargeted small TLB, see #70) reads/writes these via the chip
//! TLB on the picker tile. The constants here MUST match the
//! firmware header — the hardware-test path verifies them by
//! reading `MAGIC_VALUE` at the expected offsets.
//!
//! Module-wide `#![allow(dead_code)]` — wire-format constants are
//! intentionally retained even when the current crate path doesn't
//! reach all of them.
#![allow(dead_code)]

/// The embedded M3 firmware bytes, produced by
/// `brisc-firmware/Makefile` and surfaced via `build.rs`.
pub const VIRTIO_FIRMWARE: &[u8] = include_bytes!(env!("BRISC_VIRTIO_BIN"));

// `FW_BUILD_ID` is generated by `build.rs` (mirroring the Makefile's
// algorithm) and embedded as the upper 24 bits of
// `BRISC_VIRTIO_FW_VERSION` on the firmware side. The daemon's
// `adopt_running` refuses to take over a chip-side BRISC whose
// build_id doesn't match — the "daemon was rebuilt with new firmware
// sources but the chip still has the prior build" case.
include!(concat!(env!("OUT_DIR"), "/fw_build_id.rs"));

// ----- L1 layout -----

pub const CODE_BASE: u32 = 0x0000_0000;
pub const CODE_SIZE: u32 = 0x0000_4000;

pub const STATS_BASE: u32 = 0x0000_4000;
pub const STATS_SIZE: u32 = 0x0000_1000;

pub const REGS_BASE: u32 = 0x0001_0000;
pub const REGS_PER_DEV: u32 = 0x0000_1000;

pub const NUM_L2CPUS: u32 = 4;
/// Eight device slots per L2CPU. Six are populated: blk / net / console
/// / rng (the original four) plus two extra blk slots (BLK1 / BLK2)
/// used for the cloud-init NoCloud seed (#82) and a persistent data
/// volume (#81). The remaining two slots are unused.
///
/// The bump from 4 to 8 (rather than 6) keeps the value a power of
/// two so `slot % DEVS_PER_L2CPU` stays a bitmask AND on the BRISC
/// firmware side — modulo by a non-power-of-two would generate an
/// `__umodsi3` libgcc call the bare-metal toolchain doesn't link.
///
/// Mirrored in `BRISC_VIRTIO_DEVS_PER_L2CPU` in
/// `brisc-firmware/include/virtio_layout.h`. SHADOW_BASE moved to
/// 0x40000 to clear the larger reg-file region — see
/// `_LAYOUT_INVARIANTS` below.
pub const DEVS_PER_L2CPU: u32 = 8;
pub const NUM_SLOTS: u32 = NUM_L2CPUS * DEVS_PER_L2CPU;

pub const PER_L2CPU_WINDOW_SIZE: u32 = DEVS_PER_L2CPU * REGS_PER_DEV;

// ----- Device-index assignment within an L2CPU's window -----

pub const DEV_BLK: u32 = 0;
pub const DEV_NET: u32 = 1;
pub const DEV_CONSOLE: u32 = 2;
pub const DEV_RNG: u32 = 3;
/// Second virtio-blk slot — used for the cloud-init NoCloud seed
/// (serial="cidata") and as the first attach surface for an
/// operator-supplied data disk.
pub const DEV_BLK1: u32 = 4;
/// Third virtio-blk slot — additional operator-supplied data disk.
pub const DEV_BLK2: u32 = 5;

#[inline]
pub fn slot(l2cpu_idx: u32, device_idx: u32) -> u32 {
    l2cpu_idx * DEVS_PER_L2CPU + device_idx
}

#[inline]
pub fn slot_regs_base(slot: u32) -> u32 {
    REGS_BASE + slot * REGS_PER_DEV
}

#[inline]
pub fn l2cpu_window_base(l2cpu_idx: u32) -> u32 {
    REGS_BASE + l2cpu_idx * PER_L2CPU_WINDOW_SIZE
}

